-- Migration 0006: payment-anchored membership periods (PLAN.md Phase 1, B1–B12)
--
-- Replaces calendar-month billing. A payment now creates a membership period
-- [start_date, end_date) that grants the plan's credits.
--
-- BEFORE RUNNING IN PRODUCTION: `npm run db:cutover-dry-run -- --prod` runs
-- this whole file inside a transaction, prints what it would do, and rolls
-- back. Review the "members without a current period" list with the gym.
--
-- Apply in the Supabase SQL editor as one script (it runs as a single
-- transaction). Remove the Vercel cron in the same deploy.
--
-- Legacy columns (payment_records.period_start/period_end/status/
-- enrollment_id, gym_settings.auto_generate_payments) and the enrollments
-- table are kept untouched for rollback safety and dropped in a later
-- migration once the cutover is verified.

CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;

-- ─── Settings ─────────────────────────────────────────────────────────────────

ALTER TABLE gym_settings
  ADD COLUMN grace_days integer NOT NULL DEFAULT 0 CHECK (grace_days >= 0),
  -- Day this gym switched to periods. Grace counts from whichever is later,
  -- the member's own expiry or this date, and visits before it never count
  -- against a new period: payments weren't always recorded under the old
  -- model. New gyms get their creation date, which is a no-op.
  ADD COLUMN billing_cutover_date date NOT NULL DEFAULT CURRENT_DATE;

UPDATE gym_settings gs SET billing_cutover_date = (now() AT TIME ZONE g.timezone)::date
FROM gyms g WHERE g.id = gs.gym_id;

-- ─── Payments: only money actually received ───────────────────────────────────

ALTER TABLE payment_records
  ALTER COLUMN period_start DROP NOT NULL,
  ALTER COLUMN period_end DROP NOT NULL,
  ALTER COLUMN status SET DEFAULT 'paid';

UPDATE payment_records SET paid_at = period_start
WHERE status = 'paid' AND paid_at IS NULL;

-- Rows generated by the monthly cron that were never paid.
DELETE FROM payment_records WHERE status IN ('pending', 'overdue');

ALTER TABLE payment_records ALTER COLUMN paid_at SET NOT NULL;

CREATE INDEX payment_records_gym_paid_at_idx ON payment_records (gym_id, paid_at);

-- ─── Periods ──────────────────────────────────────────────────────────────────

CREATE TABLE membership_periods (
  id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  gym_id          uuid NOT NULL REFERENCES gyms(id) ON DELETE CASCADE,
  member_id       uuid NOT NULL REFERENCES members(id) ON DELETE CASCADE,
  payment_id      uuid NOT NULL UNIQUE REFERENCES payment_records(id) ON DELETE CASCADE,
  plan_id         uuid NOT NULL REFERENCES membership_plans(id),
  -- Snapshot of the plan at payment time (B7): later plan edits don't change paid periods.
  plan_type       plan_type NOT NULL,
  credits_granted integer,
  price_ars       integer NOT NULL,
  -- Gym-local calendar dates; end_date is exclusive (paid Oct 5 → end Nov 5, valid through Nov 4).
  start_date      date NOT NULL,
  end_date        date NOT NULL,
  -- Day of month renewals land on; kept across contiguous renewals (B4).
  anchor_day      smallint NOT NULL CHECK (anchor_day BETWEEN 1 AND 31),
  created_at      timestamptz NOT NULL DEFAULT now(),
  CHECK (end_date > start_date),
  CHECK ((plan_type = 'credits') = (credits_granted IS NOT NULL)),
  CONSTRAINT membership_periods_no_overlap
    EXCLUDE USING gist (member_id WITH =, daterange(start_date, end_date) WITH &&)
);

CREATE INDEX membership_periods_member_start_idx ON membership_periods (gym_id, member_id, start_date);
CREATE INDEX membership_periods_gym_end_idx ON membership_periods (gym_id, end_date);

-- Convert each paid payment into a period, member by member in payment order,
-- applying the same rules as lib/domain/period-math.ts:
--   paid while the previous period is running (or on its due date) → queue after it, keep anchor
--   otherwise → start on the payment date, anchor = that day
-- The plan comes from the payment's enrollment, else the member's latest enrollment.
DO $$
DECLARE
  r           record;
  cur_member  uuid;
  last_end    date;
  last_anchor int;
  s           date;
  a           int;
  e           date;
BEGIN
  FOR r IN
    SELECT pr.id, pr.gym_id, pr.member_id, pr.amount_ars,
           (pr.paid_at AT TIME ZONE g.timezone)::date AS pay_date,
           mp.id AS plan_id, mp.plan_type, mp.credits_per_month
    FROM payment_records pr
    JOIN gyms g ON g.id = pr.gym_id
    JOIN LATERAL (
      SELECT en.plan_id FROM enrollments en
      WHERE en.member_id = pr.member_id AND en.gym_id = pr.gym_id
      ORDER BY COALESCE(en.id = pr.enrollment_id, false) DESC, en.active DESC, en.started_at DESC
      LIMIT 1
    ) plan_ref ON true
    JOIN membership_plans mp ON mp.id = plan_ref.plan_id
    ORDER BY pr.member_id, pr.paid_at, pr.id
  LOOP
    IF cur_member IS DISTINCT FROM r.member_id THEN
      cur_member := r.member_id;
      last_end := NULL;
      last_anchor := NULL;
    END IF;

    IF last_end IS NOT NULL AND r.pay_date <= last_end THEN
      s := last_end;
      a := last_anchor;
    ELSE
      s := r.pay_date;
      a := extract(day FROM r.pay_date)::int;
    END IF;

    -- Anchor day in the following month, clamped to that month's length.
    e := (date_trunc('month', s) + interval '1 month')::date
         + (least(a, extract(day FROM date_trunc('month', s) + interval '2 months' - interval '1 day')::int) - 1);

    INSERT INTO membership_periods
      (gym_id, member_id, payment_id, plan_id, plan_type, credits_granted, price_ars,
       start_date, end_date, anchor_day)
    VALUES
      (r.gym_id, r.member_id, r.id, r.plan_id, r.plan_type,
       CASE WHEN r.plan_type = 'credits' THEN COALESCE(r.credits_per_month, 0) END,
       r.amount_ars, s, e, a);

    last_end := e;
    last_anchor := a;
  END LOOP;
END $$;

-- ─── Visits: gym-local date, one per day, linked to the period it consumed ───

ALTER TABLE visits
  ADD COLUMN visit_date date,
  ADD COLUMN period_id uuid REFERENCES membership_periods(id) ON DELETE SET NULL;

UPDATE visits v SET visit_date = (v.visited_at AT TIME ZONE g.timezone)::date
FROM gyms g WHERE g.id = v.gym_id;

-- Same-day duplicates (double taps before this constraint existed): keep the earliest.
DELETE FROM visits v
USING visits w
WHERE v.member_id = w.member_id
  AND v.visit_date = w.visit_date
  AND (v.visited_at, v.id) > (w.visited_at, w.id);

ALTER TABLE visits ALTER COLUMN visit_date SET NOT NULL;
ALTER TABLE visits ADD CONSTRAINT visits_member_day_unique UNIQUE (member_id, visit_date);

UPDATE visits v SET period_id = p.id
FROM membership_periods p
WHERE p.member_id = v.member_id
  AND v.visit_date >= p.start_date
  AND v.visit_date < p.end_date;

CREATE INDEX visits_period_idx ON visits (period_id);
CREATE INDEX visits_gym_date_idx ON visits (gym_id, visit_date);

-- ─── member_standing: the single source of truth for "can this member train" ─
--
-- One row per member. The reference period is the one containing today, else
-- the latest one that started, else the earliest future one.
--   status: active | grace | expired | no_plan | not_started
--   credits_left: null for unlimited plans or no period
--   grace_visits: visits since grace started, not yet attached to a period
--   Grace starts at GREATEST(end_date, billing_cutover_date); GREATEST skips
--   NULLs, so a gym without settings counts from end_date.

CREATE VIEW member_standing AS
WITH base AS (
  SELECT m.id AS member_id,
         m.gym_id,
         m.active AS member_active,
         (now() AT TIME ZONE g.timezone)::date AS today,
         COALESCE(gs.grace_days, 0) AS grace_days,
         gs.billing_cutover_date,
         COALESCE(gs.allow_over_limit, false) AS allow_over_limit
  FROM members m
  JOIN gyms g ON g.id = m.gym_id
  LEFT JOIN gym_settings gs ON gs.gym_id = m.gym_id
)
SELECT
  b.member_id,
  b.gym_id,
  b.member_active,
  b.today,
  b.grace_days,
  b.allow_over_limit,
  p.id AS period_id,
  p.plan_id,
  mp.name AS plan_name,
  p.plan_type,
  p.credits_granted,
  p.price_ars,
  p.start_date,
  p.end_date,
  p.anchor_day,
  COALESCE(u.credits_used, 0) AS credits_used,
  COALESCE(adj.total, 0) AS credits_adjusted,
  CASE WHEN p.plan_type = 'credits'
       THEN p.credits_granted - COALESCE(u.credits_used, 0) + COALESCE(adj.total, 0)
  END AS credits_left,
  COALESCE(gv.n, 0) AS grace_visits,
  st.status,
  CASE WHEN st.status = 'active' THEN p.end_date - b.today END AS days_left,
  CASE WHEN st.status IN ('grace', 'expired') THEN b.today - p.end_date END AS days_since_expiry,
  CASE WHEN st.status = 'grace'
       THEN b.grace_days - (b.today - GREATEST(p.end_date, b.billing_cutover_date))
  END AS grace_days_left,
  EXISTS (
    SELECT 1 FROM membership_periods q
    WHERE q.member_id = b.member_id AND q.start_date > b.today
  ) AS has_upcoming
FROM base b
LEFT JOIN LATERAL (
  SELECT * FROM membership_periods p
  WHERE p.member_id = b.member_id AND p.gym_id = b.gym_id
  ORDER BY (p.start_date <= b.today) DESC,
           CASE WHEN p.start_date <= b.today THEN p.start_date END DESC NULLS LAST,
           p.start_date ASC
  LIMIT 1
) p ON true
LEFT JOIN membership_plans mp ON mp.id = p.plan_id
LEFT JOIN LATERAL (
  SELECT count(*)::int AS credits_used
  FROM visits v
  WHERE v.period_id = p.id AND v.over_limit = false
) u ON true
LEFT JOIN LATERAL (
  SELECT sum(a.amount)::int AS total
  FROM credit_adjustments a
  WHERE a.member_id = b.member_id
    AND a.date >= p.start_date
    AND a.date < p.end_date
) adj ON true
LEFT JOIN LATERAL (
  SELECT count(*)::int AS n
  FROM visits v
  WHERE v.member_id = b.member_id
    AND v.period_id IS NULL
    AND v.visit_date >= GREATEST(p.end_date, b.billing_cutover_date)
) gv ON true
CROSS JOIN LATERAL (
  SELECT CASE
    WHEN p.id IS NULL                            THEN 'no_plan'
    WHEN b.today < p.start_date                  THEN 'not_started'
    WHEN b.today < p.end_date                    THEN 'active'
    WHEN b.today - GREATEST(p.end_date, b.billing_cutover_date) < b.grace_days THEN 'grace'
    ELSE 'expired'
  END AS status
) st;
